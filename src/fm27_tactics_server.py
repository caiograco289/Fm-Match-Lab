class MatchBase:
    """The match a scenario is edited against: the bundled fixture, or a match saved by FM27 (macOS: saved matches).
    snapshot: the host's match-input dump (Windows format); for the fixture, upstream's three editor snapshots.
    natural: a saved match keeps every stored player value and its own engine version word; edits are written on top
    (no controlled start, no manual-input flag), so an unedited scenario replays the saved match exactly."""
    def __init__(self,key,snapshot,pkm,natural,label='',advanced=None,setpiece_snapshot=None,team_names=None,info=None):
        self.key=key;self.snapshot=snapshot;self.pkm=Path(pkm);self.natural=natural;self.label=label;self.info=info or {}
        self.advanced=advanced or snapshot;self.oop_map=oop_maps(snapshot)
        self.cohesion=[profiles.cohesion_range(int.from_bytes(bytes.fromhex(t['header_hex'])[0x121:0x122],'little',signed=True))for t in snapshot['teams']]
        self.setpieces=[setpieces.defaults(side,(setpiece_snapshot or snapshot)['teams'][side]if natural or setpiece_snapshot else None)for side in (0,1)]
        self.engine_path='fixture'if natural else ENGINE_PATH
        self.default=defaults(self,team_names)

def defaults(base=None,team_names=None):
    base=base or BUNDLED_PARTS;teams=[]
    for side,t in enumerate(base.snapshot['teams']):
        creator=bytes.fromhex(t['creator_hex']);bits=int.from_bytes(creator[:16],'little')
        instructions={}
        for g in GROUPS.values():
            active=[o['id']for o in g['options'] if o['native_bit'] and bits>>o['native_bit']&1]
            if len(active)>1:raise ValueError('ambiguous fixture team instruction')
            instructions[str(g['id'])]=active[0] if active else next((o['id']for o in g['options'] if not o['native_bit']),g['options'][0]['id'])
        phases=[]
        for phase in range(2):
            cells=[]
            for i in range(11):
                native_slot=base.oop_map[side][i] if phase else i
                h=t['tactical_slots'][phase][native_slot]

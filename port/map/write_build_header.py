"""Write port/mac_host/fm27_mac_x86_64_<build>.h from update_rvas.py output (addresses and metadata only).

The engine version word is read from the new match constructor (the immediate it stores at +0xa2c), and refused
unless exactly one such store is found.

  python port/map/write_build_header.py RVA_UPDATE.json NEW_SLICE BUILD GAME_VERSION
"""
import json, re, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import update_rvas

ROOT = Path(__file__).resolve().parents[2]
UNUSED = {'fn_exec_build', 'fn_exec_sample'}   # reference only in the host (never called)


def main():
    table, slice_path, build, version = json.load(open(sys.argv[1])), sys.argv[2], int(sys.argv[3]), sys.argv[4]
    located = Path(sys.argv[1]).with_name('exec_locate.json')   # port/map/exec_locate.py, for the two reference entries
    if located.exists():
        for name, entry in json.load(open(located)).items():
            if entry.get('new') and table[name].get('new') is None:
                table[name].update(new=entry['new'], method=f'exec_locate votes {entry["votes"]}')
    img = update_rvas.Image(slice_path)
    uuid = table['_uuid']['new']; assert uuid == img.uuid
    ctor = int(table['fn_match_ctor']['new'], 16)
    words = {int(m, 16) for i in img.insns(ctor) for m in re.findall(r'mov qword ptr \[r\w+ \+ 0xa2c\], (0x[0-9a-f]+)', f'{i.mnemonic} {i.op_str}')}
    if len(words) != 1: raise SystemExit(f'engine version word not unique in the constructor: {words}')
    word = words.pop()
    lines = [f'// FM27 {version}, macOS game_plugin x86_64 slice (LC_UUID {uuid[:8]}-{uuid[8:12]}-{uuid[12:16]}-{uuid[16:20]}-{uuid[20:]}).',
             '// Generated by port/map/write_build_header.py from port/map/update_rvas.py (27.0.0+2493426 -> this build).',
             '// Addresses and metadata only; evidence per entry in $FM27_WORK_DIR/mac/<build>/rva_update.json.',
             '#pragma once',
             '#define FM27_RVA(name, value) FM27_RVA_##name',
             '#define FM27_MAC_UUID ' + ','.join(f'0x{uuid[i:i + 2]}' for i in range(0, 32, 2)),
             f'#define FM27_MAC_ENGINE_VERSION 0x{word:08x}u   // match constructor ({hex(ctor)}) writes it at +0xa2c',
             f'#define FM27_MAC_GAME_VERSION "{version}"']
    for name, entry in table.items():
        if name.startswith('_') or name.startswith('segment'): continue
        how = entry.get('method', '')
        if entry.get('new') is None:
            if name not in UNUSED: raise SystemExit(f'{name}: not found and used by the host')
            lines.append(f'#define FM27_RVA_{name} 0   // not found ({how}); reference only, never called')
            continue
        note = how + (f'; callers {entry["callers"]}' if 'callers' in entry and not how.startswith('callers') else '')
        if entry.get('conflict'): raise SystemExit(f'{name}: signature and callers disagree; resolve by hand')
        lines.append(f'#define FM27_RVA_{name} {entry["new"]}   // {note}' + ('; reference only' if name in UNUSED else ''))
    seg = {k.split()[1]: v['new'] for k, v in table.items() if k.startswith('segment')}
    lines += [f'#define FM27_RVA_seg_data_const_begin {seg["__DATA_CONST"][0]}',
              f'#define FM27_RVA_seg_data_const_end {seg["__DATA_CONST"][1]}',
              f'#define FM27_RVA_image_text_end {seg["__TEXT"][1]}']
    out = ROOT / f'port/mac_host/fm27_mac_x86_64_{build}.h'
    out.write_text('\n'.join(lines) + '\n')
    print(out, f'engine version 0x{word:08x}', len(lines))


if __name__ == '__main__':
    main()
